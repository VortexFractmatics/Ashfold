export const ITEMS: Record<string, ItemDef> = Object.fromEntries(
  Object.entries(RAW).map(([id, s]) => [id, pack(id, s)]),
);

export function item(id: string): ItemDef {
  return ITEMS[id] ?? pack(id, { n: id.replace(/_/g, " "), gp: 1, x: "A thing." });
}

export function isFood(id: string): boolean {
  return item(id).heal > 0;
}

export function isHatchet(id: string): boolean {
  return id.endsWith("hatchet");
}
export function isPick(id: string): boolean {
  return id.endsWith("pickaxe") || id === "mason_pick";
}
export function isNet(id: string): boolean {
  return id === "small_net";
}
export function isRod(id: string): boolean {
  return id === "fishing_rod";
}
export function isHarpoon(id: string): boolean {
  return id === "harpoon";
}
export function isBow(id: string): boolean {
  return id.includes("bow") && !id.includes("bowstring");
}
export function isStaff(id: string): boolean {
  return id.includes("staff");
}
export function isArrow(id: string): boolean {
  return id.endsWith("arrow");
}
