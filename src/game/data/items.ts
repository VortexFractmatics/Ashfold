import type { ItemDef, SkillId, WearSlot } from "../types";

type Spec = {
  n: string;
  slot?: WearSlot;
  stack?: boolean;
  gp: number;
  atk?: number;
  str?: number;
  def?: number;
  heal?: number;
  need?: [SkillId, number];
  x: string;
};

function pack(id: string, s: Spec): ItemDef {
  const wear = Boolean(s.slot);
  return {
    id,
    name: s.n,
    slot: s.slot ?? null,
    stack: s.stack ?? !wear,
    gp: s.gp,
    atk: s.atk ?? 0,
    str: s.str ?? 0,
    def: s.def ?? 0,
    heal: s.heal ?? 0,
    need: s.need ? { skill: s.need[0], level: s.need[1] } : undefined,
    examine: s.x,
  };
}

